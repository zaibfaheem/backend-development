
// JavaScript Variables

// var variable
var name = "Ali";

// let variable
let age = 20;

// const variable
const country = "Pakistan";

console.log(name);
console.log(age);
console.log(country);

// JavaScript Data Types

// String: Text written inside quotes
let studentName = "Ali";
console.log(studentName);
console.log(typeof studentName);


// Number: Numbers, including integers and decimals
let marks = 85;
console.log(marks);
console.log(typeof marks);


// Boolean: Represents true or false
let isStudent = true;
console.log(isStudent);
console.log(typeof isStudent);


// Undefined: A variable declared but no value is assigned
let result;
console.log(result);
console.log(typeof result);


// Null: Represents an intentional empty value
let address = null;
console.log(address);
console.log(typeof address);


// Object: Stores data in key-value pairs
let student = {
    name: "Ali",
    age: 20
};
console.log(student);
console.log(typeof student);


// Array: Stores multiple values in one variable
let fruits = ["Apple", "Banana", "Mango"];
console.log(fruits);
console.log(typeof fruits);


// Symbol: Creates a unique value
let id = Symbol("studentId");
console.log(id);
console.log(typeof id);


// BigInt: Used for very large integers
let bigNumber = 12345678901234567890n;
console.log(bigNumber);
console.log(typeof bigNumber);
